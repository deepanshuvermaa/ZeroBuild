import { useState, useEffect, useRef } from 'react';
import Editor from '@monaco-editor/react';
import { Code2, Eye, Save, Copy, Download, RefreshCw } from 'lucide-react';
import { useBuilderStore } from '@/store/builderStore';

interface ProfessionalCodeEditorProps {
  onSave?: (code: any) => void;
}

function generateHTML(config: any): string {
  const { theme, sections, metadata } = config;
  const sorted = [...(sections || [])].sort((a: any, b: any) => a.order - b.order);

  let sectionsHTML = '';
  for (const section of sorted) {
    const p = section.props || {};
    const heading = p.heading || p.title || '';
    const subheading = p.subheading || p.subtitle || p.description || '';
    const bg = p.backgroundColor || '#ffffff';
    const text = p.textColor || '#1f2937';

    switch (section.type) {
      case 'HeroSection':
        sectionsHTML += `  <section class="hero" style="background:${bg};color:${text};background-image:url('${p.backgroundImage || ''}');background-size:cover;background-position:center;">
    <div class="hero-overlay"></div>
    <div class="hero-content">
      <h1>${heading}</h1>
      <p>${subheading}</p>
      ${p.ctaText ? `<a href="${p.ctaLink || '#'}" class="btn-primary">${p.ctaText}</a>` : ''}
    </div>
  </section>\n`;
        break;
      case 'AboutSection':
        sectionsHTML += `  <section class="about" style="background:${bg};color:${text};">
    <div class="container">
      <div class="about-grid">
        <div class="about-text">
          <h2>${heading}</h2>
          <p>${subheading}</p>
          <p>${p.description || ''}</p>
        </div>
        ${p.image ? `<div class="about-image"><img src="${p.image}" alt="${heading}" /></div>` : ''}
      </div>
    </div>
  </section>\n`;
        break;
      case 'FooterSection':
        sectionsHTML += `  <footer style="background:${bg || '#1f2937'};color:${text || '#ffffff'};">
    <div class="container">
      <h3>${p.businessName || p.companyName || ''}</h3>
      <p>${p.tagline || p.description || ''}</p>
      <p>${p.email || ''} | ${p.phone || ''}</p>
      <p>${p.address || ''}</p>
    </div>
  </footer>\n`;
        break;
      default:
        // Generic section
        const items = p.services || p.features || p.cards || p.categories || p.testimonials || p.offers || p.stats || p.faqs || [];
        sectionsHTML += `  <section class="section-${section.type.replace('Section', '').toLowerCase()}" style="background:${bg};color:${text};">
    <div class="container">
      <h2>${heading}</h2>
      <p class="section-subtitle">${subheading}</p>
      ${Array.isArray(items) ? `<div class="grid">${items.map((item: any) => `
        <div class="card">
          ${item.image ? `<img src="${item.image}" alt="${item.title || item.name || ''}" />` : ''}
          ${item.icon ? `<span class="icon">${item.icon}</span>` : ''}
          <h3>${item.title || item.name || item.question || ''}</h3>
          <p>${item.description || item.content || item.answer || item.price || ''}</p>
        </div>`).join('')}
      </div>` : ''}
    </div>
  </section>\n`;
    }
  }

  return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1.0" />
  <title>${metadata?.projectName || 'Website'}</title>
  <link href="https://fonts.googleapis.com/css2?family=${(theme?.fontFamily || 'Inter').replace(' ', '+')}&display=swap" rel="stylesheet" />
  <link rel="stylesheet" href="styles.css" />
</head>
<body>
${sectionsHTML}
  <script src="script.js"><\/script>
</body>
</html>`;
}

