function generateJS(): string {
  return `// Generated by ZeroBuild
document.addEventListener('DOMContentLoaded', () => {
  // Smooth scroll for anchor links
  document.querySelectorAll('a[href^="#"]').forEach(link => {
    link.addEventListener('click', (e) => {
      e.preventDefault();
      const target = document.querySelector(link.getAttribute('href'));
      if (target) target.scrollIntoView({ behavior: 'smooth' });
    });
  });

  // Scroll reveal animation
  const observer = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        entry.target.style.opacity = '1';
        entry.target.style.transform = 'translateY(0)';
      }
    });
  }, { threshold: 0.1 });

  document.querySelectorAll('section, .card').forEach(el => {
    el.style.opacity = '0';
    el.style.transform = 'translateY(20px)';
    el.style.transition = 'opacity 0.6s ease, transform 0.6s ease';
    observer.observe(el);
  });
});`;
}

export const ProfessionalCodeEditor: React.FC<ProfessionalCodeEditorProps> = ({ onSave }) => {
  const { config } = useBuilderStore();
  const [activeTab, setActiveTab] = useState<'html' | 'css' | 'js'>('html');
  const [showPreview, setShowPreview] = useState(false);
  const [htmlCode, setHtmlCode] = useState('');
  const [cssCode, setCssCode] = useState('');
  const [jsCode, setJsCode] = useState('');
  const iframeRef = useRef<HTMLIFrameElement>(null);

  // Regenerate code when config changes
  useEffect(() => {
    setHtmlCode(generateHTML(config));
    setCssCode(generateCSS(config));
    setJsCode(generateJS());
  }, [config]);

  const getPreviewDoc = () => {
    return `<!DOCTYPE html><html><head><style>${cssCode}</style></head><body>${htmlCode.replace(/<!DOCTYPE[\s\S]*?<body>/, '').replace(/<\/body>[\s\S]*/, '').replace(/<link[^>]*styles\.css[^>]*>/, '').replace(/<script[^>]*script\.js[^>]*><\/script>/, '')}</body><script>${jsCode}<\/script></html>`;
  };

  const refreshPreview = () => {
    if (iframeRef.current) {
      iframeRef.current.srcdoc = getPreviewDoc();
    }
  };

  useEffect(() => { if (showPreview) refreshPreview(); }, [showPreview, htmlCode, cssCode, jsCode]);

  const handleCopy = () => {
    const code = activeTab === 'html' ? htmlCode : activeTab === 'css' ? cssCode : jsCode;
    navigator.clipboard.writeText(code);
  };

  const handleDownload = () => {
    const files = [
      { name: 'index.html', content: htmlCode },
      { name: 'styles.css', content: cssCode },
      { name: 'script.js', content: jsCode },
    ];
    files.forEach(f => {
      const blob = new Blob([f.content], { type: 'text/plain' });
      const a = document.createElement('a');
      a.href = URL.createObjectURL(blob);
      a.download = f.name;
      a.click();
    });
  };

  const currentCode = activeTab === 'html' ? htmlCode : activeTab === 'css' ? cssCode : jsCode;
  const setCurrentCode = activeTab === 'html' ? setHtmlCode : activeTab === 'css' ? setCssCode : setJsCode;

  return (
    <div className="flex-1 flex h-full bg-[#1e1e1e]">
      {/* Code Panel */}
      <div className={`flex flex-col ${showPreview ? 'w-1/2' : 'w-full'}`}>
        {/* Tabs + Actions */}
        <div className="flex items-center justify-between px-2 py-1.5 bg-[#252526] border-b border-[#333]">
          <div className="flex items-center gap-0.5">
            {(['html', 'css', 'js'] as const).map(tab => (
              <button key={tab} onClick={() => setActiveTab(tab)}
                className={`px-3 py-1.5 text-xs font-medium rounded transition-colors ${activeTab === tab ? 'bg-[#1e1e1e] text-white' : 'text-gray-400 hover:text-white'}`}>
                {tab === 'html' ? 'index.html' : tab === 'css' ? 'styles.css' : 'script.js'}
              </button>
            ))}
          </div>
          <div className="flex items-center gap-1">
            <button onClick={() => setShowPreview(!showPreview)} className={`p-1.5 rounded text-xs transition-colors ${showPreview ? 'bg-blue-600 text-white' : 'text-gray-400 hover:text-white hover:bg-white/10'}`} title="Toggle Preview">
              <Eye className="w-3.5 h-3.5" />
            </button>
            <button onClick={handleCopy} className="p-1.5 rounded text-gray-400 hover:text-white hover:bg-white/10" title="Copy"><Copy className="w-3.5 h-3.5" /></button>
            <button onClick={handleDownload} className="p-1.5 rounded text-gray-400 hover:text-white hover:bg-white/10" title="Download All"><Download className="w-3.5 h-3.5" /></button>
          </div>
        </div>

        {/* Monaco Editor */}
        <div className="flex-1 min-h-0">
          <Editor
            height="100%"
            language={activeTab === 'html' ? 'html' : activeTab === 'css' ? 'css' : 'javascript'}
            theme="vs-dark"
            value={currentCode}
            onChange={(v) => setCurrentCode(v || '')}
            options={{ fontSize: 13, minimap: { enabled: false }, wordWrap: 'on', scrollBeyondLastLine: false, automaticLayout: true, tabSize: 2 }}
          />
        </div>
      </div>

      {/* Live Preview */}
      {showPreview && (
        <div className="w-1/2 flex flex-col border-l border-[#333]">
          <div className="flex items-center justify-between px-3 py-1.5 bg-[#252526] border-b border-[#333]">
            <span className="text-xs text-gray-400">Live Preview</span>
            <button onClick={refreshPreview} className="p-1 rounded text-gray-400 hover:text-white hover:bg-white/10"><RefreshCw className="w-3.5 h-3.5" /></button>
          </div>
          <div className="flex-1 bg-white">
            <iframe ref={iframeRef} srcDoc={getPreviewDoc()} className="w-full h-full border-0" title="Preview" sandbox="allow-scripts" />
          </div>
        </div>
      )}
    </div>
  );
};
